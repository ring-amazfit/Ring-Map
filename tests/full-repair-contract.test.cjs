const assert = require('assert')
const fs = require('fs')

const androidListener = fs.readFileSync('android/app/src/main/java/com/ringmap/nav/NavNotificationListener.java', 'utf8')
const androidMain = fs.readFileSync('android/app/src/main/java/com/ringmap/nav/MainActivity.java', 'utf8')
const service = fs.readFileSync('android/app/src/main/java/com/ringmap/nav/NavigationService.java', 'utf8')
const app = fs.readFileSync('app.js', 'utf8')
const home = fs.readFileSync('page/home.js', 'utf8')
const navigation = fs.readFileSync('page/navigation.js', 'utf8')
const settings = fs.readFileSync('page/settings.js', 'utf8')
const settingPage = fs.readFileSync('setting/index.js', 'utf8')
const icons = fs.readFileSync('utils/icons.js', 'utf8')
const config = JSON.parse(fs.readFileSync('app.json', 'utf8'))

assert(androidListener.includes('LastNavCache.setListenerConnected(true'), 'connected callback must update the real listener state')
assert(androidListener.includes('LastNavCache.setListenerConnected(false'), 'disconnected callback must update the real listener state')
assert(service.includes('START_STICKY'), 'navigation service must remain sticky in the background')
assert(androidMain.includes('后台') || androidMain.includes('电池'), 'phone app must explain OEM background permissions')
assert(!home.includes('setInterval(function() { self.refreshStatus() }, 300)'), 'home must not use a high-frequency route-driving poller')
assert(home.includes('homePageRefresh'), 'home must subscribe to direct navigation events')
assert(!home.includes('replace({ url: \'page/navigation\''), 'home must not replace the route on every cache timestamp')
assert(!navigation.includes('setInterval(function()'), 'navigation page must not continuously redraw through a high-frequency timer')
assert(app.includes('homePageRefresh'), 'app must publish navigation changes to the active home page without polling')
assert(app.includes('session'), 'app must use a navigation session guard')
assert(navigation.includes('ARROW_Y') && navigation.includes('DISTANCE_Y'), 'navigation layout must use explicit non-overlapping vertical regions')
assert(!icons.includes('mask:'), 'Icons8 assets must not be recolored with a mask')
assert(!navigation.includes('0x0F6B3A'), 'navigation UI must not force green icon styling')
assert(settings.includes('自动进入导航') && settings.includes('骑行大字') && settings.includes('导航震动'), 'watch settings must expose practical navigation preferences')
assert(settingPage.includes('自动进入导航') && settingPage.includes('骑行大字'), 'phone-side settings must describe the practical preferences')
for (const target of ['balance', 'gtr4', 'cheetahpro', 'active2', 'trex3', 'trex3-pro']) {
  assert(config.targets[target], `missing supported device target: ${target}`)
}
console.log('full repair contract tests passed')
